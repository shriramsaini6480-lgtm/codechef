#include <bits/stdc++.h>
using namespace std;

int main(){
  int t;
  cin>>t;
  while(t--){
      int n,k;
      cin>>n>>k;
      if(k>n){
          cout<<"yes"<<endl;
      }
      else if(k==n){
          cout<<"no"<<endl;
      }
      else{
          cout<<"no"<<endl;
      }
      
  }
   
}